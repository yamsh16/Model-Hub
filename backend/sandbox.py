"""Run an uploaded GGUF model inside a locked-down Docker container and talk to it.

The model file is untrusted. llama.cpp parses it, so a crafted file could in principle exploit
a bug there; the container exists to contain that. Each model gets its own container with:

  * no network at all (`--network none`): nothing can be sent out or reached,
  * a read-only root filesystem, a small noexec tmpfs, and the weights mounted read-only,
  * every Linux capability dropped, no privilege escalation, an unprivileged user,
  * hard limits on memory (no swap), CPUs and process count,
  * no web UI, and no Jinja: this build of llama-server runs the model's *embedded* chat
    template through a Jinja engine by default, so we turn that off and use a fixed built-in
    template chosen from an allow-list.

Because the container has no network there is no port to publish. We talk to llama-server by
running `curl` *inside* the container with `docker exec`; the prompt goes in on stdin and never
appears in a command line. Every command is an argument list handed to Docker directly (no
shell), and every value in it is generated by us or checked against an allow-list.
"""
from __future__ import annotations

import json
import re
import subprocess
import threading
import time
from dataclasses import dataclass
from typing import Iterator

import config

CONTAINER_PREFIX = "modelhub-"
MANAGED_LABEL = "modelhub.managed=1"
MODEL_MOUNT = "/models/model.gguf"
SERVER_PORT = 8080

# Built-in llama.cpp chat templates we allow. The model's own embedded template is never used.
CHAT_TEMPLATES = (
    "chatml", "llama2", "llama3", "gemma", "mistral-v1", "mistral-v3", "mistral-v7",
    "phi3", "zephyr", "vicuna", "openchat",
)
DEFAULT_TEMPLATE = "chatml"


class SandboxError(Exception):
    """Starting or talking to the container failed; the message is safe to show the user."""


class SandboxUnavailable(SandboxError):
    """Docker itself is not available (not installed, or the daemon is not running)."""


@dataclass(frozen=True)
class Limits:
    memory: str  # e.g. "2g"
    cpus: float
    pids: int
    context: int  # tokens


def limits_from_config() -> Limits:
    return Limits(
        memory=config.serve_memory(), cpus=config.serve_cpus(), pids=256, context=config.serve_context()
    )


_MEMORY = re.compile(r"^(\d+)([kmg]?)$", re.IGNORECASE)


def memory_bytes(spec: str) -> int:
    m = _MEMORY.match(spec.strip())
    if not m:
        raise ValueError(f"bad memory limit {spec!r} (use e.g. 512m or 2g)")
    return int(m.group(1)) * {"": 1, "k": 1024, "m": 1024**2, "g": 1024**3}[m.group(2).lower()]


def container_name(model_id) -> str:
    return f"{CONTAINER_PREFIX}{model_id}"


def build_run_args(name: str, model_path: str, limits: Limits, template: str, labels: dict[str, str]) -> list[str]:
    """The complete `docker run` argument list. Pure and deterministic, so tests can inspect it."""
    if template not in CHAT_TEMPLATES:
        raise SandboxError(f"Unknown chat template '{template}'")
    if "," in model_path:  # would be read as another --mount option
        raise SandboxError("The upload folder path must not contain a comma")
    memory_bytes(limits.memory)  # validates the format
    args = [
        "run", "--detach", "--pull", "never", "--name", name, "--label", MANAGED_LABEL,
        # --- isolation ---
        "--network", "none",
        "--read-only", "--tmpfs", "/tmp:rw,noexec,nosuid,size=64m",
        "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
        "--user", "65534:65534", "--init",
        # --- resource limits ---
        "--memory", limits.memory, "--memory-swap", limits.memory,
        "--cpus", str(limits.cpus), "--pids-limit", str(limits.pids),
        "--log-driver", "json-file", "--log-opt", "max-size=1m", "--log-opt", "max-file=1",
    ]
    for key, value in labels.items():
        args += ["--label", f"{key}={value}"]
    args += [
        "--mount", f"type=bind,source={model_path},target={MODEL_MOUNT},readonly",
        config.serve_image(),
        "-m", MODEL_MOUNT, "--host", "127.0.0.1", "--port", str(SERVER_PORT),
        "-c", str(limits.context), "--parallel", "1", "-t", str(max(1, int(limits.cpus))),
        "--no-webui", "--no-jinja", "--chat-template", template,
    ]
    return args


# ------------------------------------------------------------------------------ Docker access

def _docker_argv(args: list[str]) -> list[str]:
    return [config.docker_bin(), *args]


_DAEMON_DOWN = ("cannot connect to the docker daemon", "error during connect", "failed to connect to the docker api",
                "is the docker daemon running")


def docker(args: list[str], *, input: bytes | None = None, timeout: float = 30) -> subprocess.CompletedProcess:
    """Run one Docker CLI command. Raises SandboxUnavailable when Docker cannot be reached."""
    try:
        done = subprocess.run(_docker_argv(args), input=input, capture_output=True, timeout=timeout, check=False)
    except FileNotFoundError:
        raise SandboxUnavailable("Docker is not installed on the server")
    except subprocess.TimeoutExpired:
        raise SandboxError("Docker did not answer in time")
    stderr = done.stderr.decode("utf-8", "replace").lower()
    if done.returncode != 0 and any(marker in stderr for marker in _DAEMON_DOWN):
        raise SandboxUnavailable("Docker is not running on the server")
    return done


def _first_line(data: bytes, limit: int = 300) -> str:
    text = data.decode("utf-8", "replace").strip()
    return (text.splitlines() or [""])[0][:limit]


def is_running(name: str) -> bool:
    done = docker(["inspect", "-f", "{{.State.Running}}", name], timeout=10)
    return done.returncode == 0 and done.stdout.decode().strip() == "true"


def _log_tail(name: str, lines: int = 3) -> str:
    done = docker(["logs", "--tail", str(lines), name], timeout=10)
    text = (done.stdout + done.stderr).decode("utf-8", "replace")
    return " | ".join(line.strip()[:200] for line in text.splitlines() if line.strip())[:600]


def start(name: str, model_path: str, limits: Limits, template: str, labels: dict[str, str]) -> None:
    """Create the container and wait until the model is loaded. Leaves nothing running on failure."""
    done = docker(build_run_args(name, model_path, limits, template, labels), timeout=60)
    if done.returncode != 0:
        detail = _first_line(done.stderr)
        if "no such image" in detail.lower() or "unable to find image" in detail.lower():
            detail = f"The model runtime image is not installed on the server (docker pull {config.serve_image()})"
        raise SandboxError(f"Could not start the model: {detail}")

    deadline = time.monotonic() + config.serve_start_timeout()
    try:
        while time.monotonic() < deadline:
            if not is_running(name):
                raise SandboxError(f"The model failed to load: {_log_tail(name) or 'the container exited'}")
            probe = docker(
                ["exec", name, "curl", "-s", "-o", "/dev/null", "-w", "%{http_code}", "--max-time", "2",
                 f"http://127.0.0.1:{SERVER_PORT}/health"],
                timeout=10,
            )
            if probe.stdout.decode().strip() == "200":
                return
            time.sleep(0.5)
        raise SandboxError("The model took too long to load")
    except BaseException:
        stop(name)
        raise


def stop(name: str) -> None:
    docker(["rm", "-f", name], timeout=30)


def stop_all_managed() -> int:
    """Remove every container this app created (leftovers from a crash). Returns how many."""
    done = docker(["ps", "-aq", "--filter", f"label={MANAGED_LABEL}"], timeout=15)
    ids = done.stdout.decode().split() if done.returncode == 0 else []
    if ids:
        docker(["rm", "-f", *ids], timeout=60)
    return len(ids)


# ----------------------------------------------------------------------------------- talking

def _exec_args(name: str, timeout: float) -> list[str]:
    return [
        "exec", "-i", name, "curl", "-sS", "-N", "--max-time", str(int(timeout)),
        f"http://127.0.0.1:{SERVER_PORT}/v1/chat/completions",
        "-H", "Content-Type: application/json", "-d", "@-",
    ]


def chat_once(name: str, payload: dict) -> str:
    """One non-streaming completion; returns the reply text."""
    timeout = config.serve_request_timeout()
    done = docker(_exec_args(name, timeout), input=json.dumps(payload).encode(), timeout=timeout + 5)
    if done.returncode != 0:
        raise SandboxError(_exec_failure(name, done))
    try:
        body = json.loads(done.stdout)
    except ValueError:
        raise SandboxError("The model returned an unreadable reply")
    if isinstance(body, dict) and "error" in body:
        err = body["error"]
        raise SandboxError(str(err.get("message", err) if isinstance(err, dict) else err)[:300])
    try:
        return body["choices"][0]["message"]["content"] or ""
    except (KeyError, IndexError, TypeError):
        raise SandboxError("The model returned an unexpected reply")


def _exec_failure(name: str, done: subprocess.CompletedProcess) -> str:
    err = done.stderr.decode("utf-8", "replace").lower()
    if "is not running" in err or "no such container" in err:
        return "The model stopped (it may have run out of memory); start it again"
    if "timed out" in err or done.returncode == 28:
        return "The model took too long to answer"
    return "The model did not answer"


def chat_stream(name: str, payload: dict) -> Iterator[str]:
    """Stream a completion as raw SSE lines (`data: {...}`), killing it if it runs too long."""
    timeout = config.serve_request_timeout()
    proc = subprocess.Popen(
        _docker_argv(_exec_args(name, timeout)),
        stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
    )
    watchdog = threading.Timer(timeout + 5, proc.kill)
    watchdog.start()
    try:
        assert proc.stdin and proc.stdout
        proc.stdin.write(json.dumps(payload).encode())
        proc.stdin.close()
        for raw in proc.stdout:
            yield raw.decode("utf-8", "replace").rstrip("\r\n")
    finally:  # also runs when the client disconnects mid-stream
        watchdog.cancel()
        proc.kill()
        proc.wait()
